import assert from 'node:assert/strict';
import { log } from 'node:console';
import { setImmediate as nextTick } from 'node:timers/promises';
import { JSDOM } from 'jsdom';
import { runtime } from './helpers/runtime.mjs';
const dom = new JSDOM('<!DOCTYPE html><body><button id="origin">settings</button></body>', { url: 'https://game.test/?secret=test' });
const { window } = dom;
window.HTMLDialogElement.prototype.showModal = function () { this.open = true; };
window.HTMLDialogElement.prototype.close = function () { this.open = false; this.dispatchEvent(new window.Event('close')); };
let copied, clipboardFail = false, opened = 0, closed = 0;
const navigator = { userAgent: 'test-browser', clipboard: { writeText: async (value) => {
  if (clipboardFail) throw new Error('denied'); copied = value;
} } };
const load = runtime({ window, document: window.document, navigator });
const { feedbackReport, mountReleaseSupport, openFeedback } = load('src/systems/ReleaseSupport.ts');
const info = { version: '0.1.0-preview.1', revision: 'test-build', builtAt: '2026-10-19', channel: 'public-preview' };
assert.equal(JSON.parse(feedbackReport(info, { levelId: 'awakening-demo' }, '')).game.level, 'awakening-demo');
const context = { levelId: 'private-map-title', character: 'bubu', health: 2, customMap: true,
  uploadedAssets: 'secret-image', progress: 'private-save' };
const report = feedbackReport(info, context, 'a'.repeat(2100));
assert.equal(JSON.parse(report).description.length, 2000);
assert.equal(JSON.parse(report).game.level, 'custom');
for (const excluded of ['secret-image', 'private-save', 'private-map-title', 'game.test', '?secret']) assert.equal(report.includes(excluded), false);
const dispose = mountReleaseSupport(info, () => context, () => opened++, () => closed++);
window.document.querySelector('#origin').focus();
openFeedback(); openFeedback(); assert.equal(opened, 1, '重复点击只打开一次');
const dialog = window.document.querySelector('dialog');
assert.equal(dialog.open, true);
dialog.querySelector('[data-description]').value = '<img src=x onerror=alert(1)>；按跳后卡住';
dialog.querySelector('[data-copy]').click(); await nextTick();
assert.match(copied, /按跳后卡住/); assert.equal(dialog.querySelector('img'), null);
assert.match(dialog.querySelector('[data-status]').textContent, /尚未在线提交/);
clipboardFail = true;
dialog.querySelector('[data-copy]').click(); await nextTick();
const output = dialog.querySelector('[data-report]');
assert.equal(output.selectionEnd, output.value.length);
assert.match(dialog.querySelector('[data-status]').textContent, /无法自动复制/);
dialog.querySelector('[data-close]').click();
assert.equal(closed, 1); assert.equal(window.document.activeElement.id, 'origin');
openFeedback(); dispose(); assert.equal(opened, 2); assert.equal(closed, 2);
assert.equal(window.document.querySelector('dialog'), null);
openFeedback(); assert.equal(opened, 2, '销毁后无全局入口残留');
window.close();
log('release support: privacy allowlist, copy fallback, focus and cleanup passed');
